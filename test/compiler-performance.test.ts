import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { createAnalysisContext } from "../src/analysis-context.js";
import { loadConfig } from "../src/config.js";
import { compilerPerformanceEvidence, validCompilerPerformanceReport } from "../src/compiler-performance.js";
import { measureTypeHealth } from "../src/measures/type-quality.js";
import { readArtifact } from "../src/writer.js";

test("compiler timings and program scope are opt-in observations with honest cache provenance", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "lens-compiler-perf-"));
  try {
    fs.mkdirSync(path.join(root, "src"));
    fs.mkdirSync(path.join(root, "scripts"));
    fs.writeFileSync(path.join(root, "package.json"), '{"name":"performance","type":"module"}');
    fs.writeFileSync(path.join(root, "src/main.ts"), "export const value: string = 'value';\n");
    fs.writeFileSync(path.join(root, "scripts/tool.ts"), "export const tool = 1;\n");
    fs.writeFileSync(path.join(root, "tsconfig.json"), JSON.stringify({ compilerOptions: { strict: true, module: "NodeNext", skipLibCheck: true }, include: ["src", "scripts"] }));
    fs.writeFileSync(path.join(root, "lens.json"), JSON.stringify({ source_roots: ["src"] }));
    const config = loadConfig(path.join(root, "lens.json"));
    const disabledProject = createAnalysisContext(config).project();
    assert.equal(compilerPerformanceEvidence(config, disabledProject).status, "disabled");
    assert.ok(disabledProject.tsProject.project_configs?.every((item) => !item.performance));
    config.typescript.measurePerformance = true;
    const context = createAnalysisContext(config);
    const first = compilerPerformanceEvidence(config, context.project());
    assert.notEqual(context.project().cache.status, "hit");
    assert.equal(first.status, "complete");
    assert.ok(validCompilerPerformanceReport(first));
    const observation = first.projects[0]!;
    assert.equal(observation.observation_reused, false);
    assert.equal(observation.program_scope?.root_files, 2);
    assert.equal(observation.program_scope?.selected_files, 1);
    assert.equal(observation.program_scope?.unselected_source_files, 1);
    assert.ok(observation.sample!.files.some((file) => file.file === "scripts/tool.ts" && file.root && !file.selected));
    assert.ok(Object.values(observation.sample!.phases_ms).every((value) => Number.isFinite(value) && value >= 0));
    assert.ok(observation.sample!.counters.types! > 0);
    assert.deepEqual(observation.sample!.checking_options, { skip_lib_check: true, skip_default_lib_check: false, no_emit: true });
    measureTypeHealth(config, "compiler performance", context);
    assert.deepEqual(readArtifact(config, "type_health.json")?.compiler_performance, first);
    assert.ok(!fs.existsSync(path.join(root, "src/main.js")));
    assert.ok(!fs.existsSync(path.join(root, "tsconfig.tsbuildinfo")));
    const cached = compilerPerformanceEvidence(config, createAnalysisContext(config).project());
    assert.equal(cached.projects[0]?.observation_reused, true);
    assert.deepEqual(cached.projects[0]?.sample, observation.sample);
    fs.appendFileSync(path.join(root, "scripts/tool.ts"), "export const extra = 2;\n");
    const changed = compilerPerformanceEvidence(config, createAnalysisContext(config).project());
    assert.equal(changed.projects[0]?.observation_reused, false);
    assert.notEqual(changed.projects[0]?.sample?.sample_id, observation.sample?.sample_id);
    const invalid = structuredClone(first);
    invalid.projects[0]!.sample!.phases_ms.diagnostics = -1;
    assert.equal(validCompilerPerformanceReport(invalid), false);
    const inconsistent = structuredClone(first);
    inconsistent.projects[0]!.program_scope!.program_files = 0;
    assert.equal(validCompilerPerformanceReport(inconsistent), false);
    fs.writeFileSync(path.join(root, "tsconfig.json"), "{ invalid");
    const unavailable = compilerPerformanceEvidence(config, createAnalysisContext(config).project());
    assert.equal(unavailable.status, "incomplete");
    assert.equal(unavailable.projects[0]?.sample, null);
    assert.ok(validCompilerPerformanceReport(unavailable));
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
});
