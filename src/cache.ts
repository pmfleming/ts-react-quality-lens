import path from "node:path";
import * as ts from "typescript";
import { databaseFile, sqlGet, sqlRun, textColumn, transaction, withStore } from "./store.js";
import { parseJson } from "./collections.js";
import { arrayOf, count, oneOf, optional, shape, string } from "./validation.js";
import { fileInput } from "./files.js";
import { compilerInputQueryResults, type CompilerInputQuery } from "./integrations/compiler-inputs.js";
import { analysisIdentity, contentHash, sourceSetHash } from "./provenance.js";
import type { Config, ProjectAnalysis, SourceFileRecord, TypedModuleRecord } from "./types.js";

const CACHE_FORMAT = 7;

type CachePayload = {
  cache_format: number;
  key: string;
  project: Omit<ProjectAnalysis, "cache" | "tsProject"> & {
    tsProject: Omit<ProjectAnalysis["tsProject"], "modules"> & {
      modules: Array<[string, TypedModuleRecord]>;
    };
  };
};

export function readAnalysisCache(
  config: Config,
  sourceFiles: SourceFileRecord[],
  testFiles: SourceFileRecord[],
): ProjectAnalysis | null {
  if (!config.cache.enabled) return null;
  const file = cacheFile(config);
  try {
    return withStore(config.cache.dir, (db) => transaction(db, () => {
      const row: unknown = sqlGet(db, "SELECT cache_key, inputs, queries FROM analysis_cache WHERE slot = 1");
      const key = textColumn(row, "cache_key");
      const inputs = parseJson(textColumn(row, "inputs") ?? "null");
      const queries = parseJson(textColumn(row, "queries") ?? "null");
      if (!Array.isArray(inputs) || !inputs.every((item): item is string => typeof item === "string") || !Array.isArray(queries)) return null;
      // Query metadata is generated by the compiler input collector; payload hydration is deferred until a key hit.
      if (!validQueries(queries) || key !== analysisCacheKey(config, sourceFiles, testFiles, inputs, queries)) return null;
      const payload = parseJson(textColumn(sqlGet(db, "SELECT payload FROM analysis_cache WHERE slot = 1"), "payload") ?? "null");
      return isCachePayload(payload) && payload.key === key ? hydrateProject(payload.project, file) : null;
    }, false));
  } catch {
    return null;
  }
}

export function writeAnalysisCache(
  config: Config,
  project: Omit<ProjectAnalysis, "cache">,
): ProjectAnalysis["cache"] {
  if (!config.cache.enabled) return disabledCache();
  const file = cacheFile(config);
  if (!cacheableProject(config, project)) {
    return { enabled: true, status: "miss", reused: false, file, previous_source_set_hash: null };
  }
  const payload: CachePayload = {
    cache_format: CACHE_FORMAT,
    key: analysisCacheKey(config, project.sourceFiles, project.testFiles, project.tsProject.input_files, project.tsProject.input_queries),
    project: {
      ...project,
      tsProject: {
        ...project.tsProject,
        modules: [...project.tsProject.modules.entries()],
      },
    },
  };
  withStore(config.cache.dir, (db) => transaction(db, () => {
    sqlRun(db, "INSERT INTO analysis_cache VALUES (1, ?, ?, ?, ?) ON CONFLICT(slot) DO UPDATE SET cache_key = excluded.cache_key, inputs = excluded.inputs, queries = excluded.queries, payload = excluded.payload",
      payload.key, JSON.stringify(project.tsProject.input_files ?? []), JSON.stringify(project.tsProject.input_queries ?? []), JSON.stringify(payload));
  }));
  return {
    enabled: true,
    status: "miss",
    reused: false,
    file,
    previous_source_set_hash: null,
  };
}

function hydrateProject(project: CachePayload["project"], file: string): ProjectAnalysis {
  const modules = project.modules;
  for (const module of modules) {
    const scriptKind = module.file.endsWith(".tsx")
      ? ts.ScriptKind.TSX
      : module.file.endsWith(".jsx") ? ts.ScriptKind.JSX : module.file.endsWith(".js") ? ts.ScriptKind.JS : ts.ScriptKind.TS;
    const ast = ts.createSourceFile(module.file, module.text, ts.ScriptTarget.Latest, true, scriptKind);
    Object.defineProperty(module, "astSourceFile", { value: ast, enumerable: false });
  }
  return {
    ...project,
    modules,
    tsProject: {
      ...project.tsProject,
      modules: new Map(project.tsProject.modules),
    },
    cache: {
      enabled: true,
      status: "hit",
      reused: true,
      file,
      previous_source_set_hash: sourceSetHash(project),
    },
  };
}

function analysisCacheKey(
  config: Config,
  sourceFiles: SourceFileRecord[],
  testFiles: SourceFileRecord[],
  inputs: string[] = [],
  queries: CompilerInputQuery[] = [],
): string {
  const measured = new Set([...sourceFiles, ...testFiles].map((file) => path.resolve(file.path)));
  const dependencies = inputs.filter((file) => !measured.has(file)).map((file) => fileInput(file, path.relative(config.projectRoot, file)));
  return contentHash([...sourceFiles, ...testFiles, ...dependencies], [
    String(CACHE_FORMAT), analysisIdentity(config).id, compilerInputQueryResults(queries),
  ]);
}

function cacheableProject(config: Config, project: Omit<ProjectAnalysis, "cache">): boolean {
  if (!project.sourceFiles.length) return false;
  if (config.tsconfig && !project.tsProject.loaded) return false;
  return project.workspaces
    .filter((workspace) => workspace.tsconfigs.length > 0)
    .every((workspace) => workspace.project_loaded);
}

function cacheFile(config: Config): string {
  return databaseFile(config.cache.dir);
}

function disabledCache(): ProjectAnalysis["cache"] {
  return { enabled: false, status: "disabled", reused: false, file: null, previous_source_set_hash: null };
}

function isCachePayload(value: unknown): value is CachePayload {
  if (!value || typeof value !== "object") return false;
  if (!("cache_format" in value) || !("key" in value) || !("project" in value)) return false;
  return value.cache_format === CACHE_FORMAT && typeof value.key === "string" && Boolean(value.project);
}

const queryShape = shape({
  kind: oneOf("fileExists", "directoryExists", "getDirectories", "realpath", "readDirectory"), path: string,
  extensions: optional(arrayOf(string)), excludes: optional(arrayOf(string)), includes: optional(arrayOf(string)), depth: optional(count),
});
const validQueries = arrayOf((value: unknown): value is CompilerInputQuery => queryShape(value));
